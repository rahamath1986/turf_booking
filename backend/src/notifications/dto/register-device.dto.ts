import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsEnum, IsNotEmpty, IsOptional, IsString } from 'class-validator';

export class RegisterDeviceDto {
  @ApiProperty({
    description: 'FCM push registration token generated by client device',
    example: 'dK8sl39dmc...fcm_registration_token',
  })
  @IsString()
  @IsNotEmpty()
  deviceToken: string;

  @ApiProperty({
    description: 'Device operating system / platform',
    enum: ['IOS', 'ANDROID', 'WEB'],
    example: 'ANDROID',
  })
  @IsEnum(['IOS', 'ANDROID', 'WEB'])
  @IsNotEmpty()
  deviceType: string;

  @ApiPropertyOptional({
    description: 'Friendly name of the device',
    example: 'Pixel 8 Pro',
  })
  @IsOptional()
  @IsString()
  deviceName?: string;

  @ApiPropertyOptional({
    description: 'Operating system version',
    example: 'Android 14',
  })
  @IsOptional()
  @IsString()
  osVersion?: string;

  @ApiPropertyOptional({
    description: 'Client app version',
    example: '1.0.0',
  })
  @IsOptional()
  @IsString()
  appVersion?: string;
}
