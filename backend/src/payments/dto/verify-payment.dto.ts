import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsNotEmpty, IsOptional, IsString, IsUUID } from 'class-validator';

export class VerifyPaymentDto {
  @ApiPropertyOptional({
    description:
      'Internal Payment record UUID (optional if orderId is provided)',
    example: '33333333-3333-3333-3333-333333333333',
  })
  @IsOptional()
  @IsUUID('4')
  paymentId?: string;

  @ApiProperty({
    description: 'Payment gateway order ID returned during create-order',
    example: 'order_mock_1727230000000_a1b2',
  })
  @IsNotEmpty()
  @IsString()
  orderId: string;

  @ApiProperty({
    description:
      'Transaction ID returned by gateway SDK after successful customer payment',
    example: 'pay_mock_9988776655',
  })
  @IsNotEmpty()
  @IsString()
  transactionId: string;

  @ApiProperty({
    description:
      'Cryptographic signature generated by gateway for verification',
    example: '4f2b988f01b2a75d5a7d9b7f3a8b9a1c0d4e5f6a7b8c9d0e1f2a3b4c5d6e7f8a',
  })
  @IsNotEmpty()
  @IsString()
  signature: string;
}
